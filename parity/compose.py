#!/usr/bin/env python3
"""Compose legacy-vs-Angular screenshots side by side and write report/README.md from results.json."""
import json
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).parent / 'report'
SCREENS = ROOT / 'screens'
OUT = ROOT / 'side-by-side'
LABEL_H = 40
GAP = 20


def compose(name: str) -> Path | None:
    left, right = SCREENS / 'legacy' / f'{name}.png', SCREENS / 'angular' / f'{name}.png'
    imgs = [Image.open(p).convert('RGB') if p.exists() else None for p in (left, right)]
    if not any(imgs):
        return None
    w = max(i.width for i in imgs if i)
    h = max(i.height for i in imgs if i)
    canvas = Image.new('RGB', (w * 2 + GAP, h + LABEL_H), 'white')
    draw = ImageDraw.Draw(canvas)
    for idx, (img, label) in enumerate(zip(imgs, ('Legacy AngularJS 1.5', 'Angular 21'))):
        x = idx * (w + GAP)
        draw.text((x + 10, 12), label if img else f'{label} (missing)', fill='black')
        if img:
            canvas.paste(img, (x, LABEL_H))
    OUT.mkdir(parents=True, exist_ok=True)
    out = OUT / f'{name}.png'
    canvas.save(out, optimize=True)
    return out


def results() -> dict[str, dict[str, str]]:
    path = ROOT / 'results.json'
    table: dict[str, dict[str, str]] = {}
    if not path.exists():
        return table

    def walk(suite, prefix=''):
        for spec in suite.get('specs', []):
            title = f"{Path(spec['file']).stem.replace('.spec', '')} › {spec['title']}"
            for t in spec['tests']:
                last = t['results'][-1]['status'] if t['results'] else 'skipped'
                expected = t.get('expectedStatus', 'passed')
                status = 'pass' if last == expected == 'passed' else (
                    'expected fail' if expected == 'failed' and last == 'failed' else last)
                table.setdefault(title, {})[t['projectName']] = status
        for child in suite.get('suites', []):
            walk(child)

    for s in json.loads(path.read_text())['suites']:
        walk(s)
    return table


def main():
    names = sorted({p.stem for p in SCREENS.glob('*/*.png')})
    composed = [n for n in names if compose(n)]
    rows = results()
    lines = ['# Parity report: legacy AngularJS vs Angular 21', '',
             'Generated by `python3 compose.py` from `report/results.json` and `report/screens/`.', '',
             '| Spec | Legacy | Angular |', '| --- | --- | --- |']
    for title, r in sorted(rows.items()):
        lines.append(f"| {title} | {r.get('legacy', '-')} | {r.get('angular', '-')} |")
    lines += ['', '## Side-by-side screenshots (legacy left, Angular right)', '']
    for n in composed:
        lines += [f'### {n}', '', f'![{n}](side-by-side/{n}.png)', '']
    (ROOT / 'README.md').write_text('\n'.join(lines))
    print(f'{len(rows)} specs, {len(composed)} side-by-side images -> {ROOT / "README.md"}')


if __name__ == '__main__':
    main()
